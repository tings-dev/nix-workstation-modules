"""Reconcile Codex reset-credit expirations into one discovered calendar."""

import argparse
from collections import defaultdict
from datetime import UTC, datetime, timedelta
import fcntl
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile

from icalendar import Calendar, Event


SOURCE = "query-codex-resets"
UID_PREFIX = "codex-reset-credit-"
DESCRIPTION = "Expiration of an available Codex reset credit. Generated by query-codex-resets."


def reset_times(output):
    values = json.loads(output)
    if not isinstance(values, list):
        raise ValueError("query-codex-resets did not return a JSON array")
    times = set()
    for value in values:
        if not isinstance(value, str):
            raise ValueError("reset expiration must be an ISO timestamp")
        instant = datetime.fromisoformat(value)
        if instant.tzinfo is None:
            raise ValueError("reset expiration needs a timezone")
        # iCalendar DATE-TIME has second precision.
        times.add(instant.astimezone(UTC).replace(microsecond=0))
    return sorted(times)


def calendar_directory(root, account, name):
    if not re.fullmatch(r"[A-Za-z0-9_]+", account):
        raise ValueError("account must be a vdirsyncer account name")
    account_dir = root / account
    if not account_dir.is_dir():
        raise ValueError(f"calendar account has not been discovered: {account}")
    matches = []
    for path in account_dir.iterdir():
        if path.name.startswith(".") or path.is_symlink() or not path.is_dir():
            continue
        displayname = path / "displayname"
        if path.name == name or (displayname.is_file() and displayname.read_text().strip() == name):
            matches.append(path)
    if len(matches) != 1:
        raise ValueError(f"expected one discovered calendar matching {name!r}, found {len(matches)}")
    return matches[0]


def uid_for(instant, domain):
    key = instant.strftime("%Y%m%dT%H%M%SZ")
    return f"{UID_PREFIX}{key}@{domain}"


def atomic_write(path, content):
    # Readers, including vdirsyncer, must never see a partially written event.
    descriptor, temporary = tempfile.mkstemp(prefix=".codex-reset-", dir=path.parent)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def reconcile(directory, times, title, domain):
    desired = {uid_for(instant, domain): instant for instant in times}
    managed = defaultdict(list)
    for path in sorted(directory.glob("*.ics")):
        calendar = Calendar.from_ical(path.read_bytes())
        events = calendar.walk("VEVENT")
        owned = [event for event in events if str(event.get("X-FRKL-SOURCE", "")) == SOURCE]
        if owned:
            other_items = [item for item in calendar.subcomponents if item.name not in {"VEVENT", "VTIMEZONE"}]
            if other_items or len(events) != 1 or len(owned) != 1 or not str(owned[0].get("UID", "")).startswith(UID_PREFIX):
                raise ValueError(f"refusing to alter a mixed or invalid generated calendar file: {path.name}")
            managed[str(owned[0]["UID"])].append((path, calendar, owned[0]))
        elif any(str(event.get("UID", "")) in desired for event in events):
            raise ValueError(f"generated UID belongs to an unmarked event: {path.name}")

    created = updated = removed = 0
    now = datetime.now(UTC).replace(microsecond=0)
    for uid, instant in desired.items():
        entries = managed.pop(uid, [])
        if entries:
            path, calendar, event = entries[0]
        else:
            path = directory / f"{uid}.ics"
            if path.exists():
                raise ValueError(f"refusing to overwrite an unrelated file: {path.name}")
            calendar = Calendar()
            calendar.add("PRODID", "-//frkl//Codex reset credits//EN")
            calendar.add("VERSION", "2.0")
            event = Event()
            event.add("UID", uid)
            event.add("CREATED", now)
            calendar.add_component(event)

        end = instant + timedelta(minutes=5)
        unchanged = (
            entries
            and event.get("DTSTART") is not None
            and event.decoded("DTSTART") == instant
            and event.get("DTEND") is not None
            and event.decoded("DTEND") == end
            and str(event.get("SUMMARY", "")) == title
            and str(event.get("DESCRIPTION", "")) == DESCRIPTION
            and str(event.get("TRANSP", "")) == "TRANSPARENT"
        )
        if not unchanged:
            for property_name, value in {
                "DTSTART": instant,
                "DTEND": end,
                "DTSTAMP": now,
                "LAST-MODIFIED": now,
                "SUMMARY": title,
                "DESCRIPTION": DESCRIPTION,
                "TRANSP": "TRANSPARENT",
                "X-FRKL-SOURCE": SOURCE,
                "SEQUENCE": int(event.get("SEQUENCE", -1)) + 1,
            }.items():
                event.pop(property_name, None)
                event.add(property_name, value)
            event.pop("DURATION", None)
            atomic_write(path, calendar.to_ical())
            if entries:
                updated += 1
            else:
                created += 1
        for duplicate, _, _ in entries[1:]:
            duplicate.unlink()
            removed += 1

    for entries in managed.values():
        for path, _, _ in entries:
            path.unlink()
            removed += 1
    return created, updated, removed


def run(args):
    directory = calendar_directory(args.calendar_root, args.account, args.calendar)
    state_root = Path(os.environ.get("XDG_STATE_HOME", str(Path.home() / ".local/state")))
    lock_dir = state_root / "codex-reset-calendar"
    lock_dir.mkdir(parents=True, exist_ok=True, mode=0o700)
    lock_name = hashlib.sha256(str(directory.resolve()).encode()).hexdigest()
    with (lock_dir / f"{lock_name}.lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        # Parse the entire successful response before changing any events.
        output = subprocess.run(
            ["query-codex-resets", "--json"], check=True, capture_output=True, text=True, timeout=90
        ).stdout
        times = reset_times(output)
        pair = f"calendar_{args.account}/{directory.name}"
        sync_env = os.environ.copy()
        sync_env.setdefault("SECRETSPEC_REASON", "Synchronize Codex reset-credit expiration events")
        if not args.no_sync:
            subprocess.run(["vdirsyncer", "sync", pair], check=True, env=sync_env, timeout=120)
        created, updated, removed = reconcile(directory, times, args.title, args.uid_domain)
        if not args.no_sync:
            subprocess.run(["vdirsyncer", "sync", pair], check=True, env=sync_env, timeout=120)
        print(f"{args.calendar}: {len(times)} reset times; {created} created, {updated} updated, {removed} removed")


def main():
    data_home = Path(os.environ.get("XDG_DATA_HOME", str(Path.home() / ".local/share")))
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--calendar", required=True, help="discovered calendar display name or collection ID")
    parser.add_argument("--uid-domain", default="localhost", help="domain used in generated event UIDs")
    parser.add_argument("--account", default="fastmail", help="personal-data calendar account (default: fastmail)")
    parser.add_argument("--calendar-root", type=Path, default=data_home / "calendars", help="local calendar replica root")
    parser.add_argument("--title", default="Codex reset credit expires", help="summary for generated five-minute events")
    parser.add_argument("--no-sync", action="store_true", help="update local events without contacting the calendar provider")
    args = parser.parse_args()
    if not re.fullmatch(r"[A-Za-z0-9.-]+", args.uid_domain):
        parser.error("--uid-domain must contain only letters, digits, dots and hyphens")
    try:
        run(args)
    except subprocess.CalledProcessError as error:
        # Query stderr can contain backend responses; do not copy it into the journal.
        print(f"{error.cmd[0]} failed (exit {error.returncode}); event refresh did not complete", file=sys.stderr)
        return 1
    except (ValueError, OSError, subprocess.TimeoutExpired) as error:
        print(f"reset calendar refresh failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
